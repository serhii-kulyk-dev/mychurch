export type Lang = "ua" | "en";

export interface ModuleItem {
  id: string;
  name: string;
  text: string;
  soon?: boolean;
}
export interface ModuleGroup {
  id: string;
  title: string;
  text: string;
  items: ModuleItem[];
}
/** One step of the looping group-chat demo on the AI page. */
export interface ChatAsk {
  kind: string;
  title: string;
  text: string;
  yes: string;
  no: string;
  done: string;
}
export type ChatCollectField = "bring" | "ride" | "prayer" | "guests";
export interface ChatStep {
  /** "bot" or an index into `members`. */
  who: "bot" | number;
  text: string;
  poll?: boolean;
  vote?: "yes" | "no";
  collect?: { field: ChatCollectField; value: string };
  ask?: ChatAsk;
  link?: string;
  replyTo?: number;
  digest?: boolean;
  /** Effects only (e.g. the evening digest): nothing is posted to the chat. */
  silent?: boolean;
}

/** One message of the looping assistant conversation on the home page. */
export interface AiChatTurn {
  who: "me" | "bot";
  text: string;
  time: string;
  /** Data the assistant returns — shown as a small table inside the bubble. */
  rows?: { k: string; v: string }[];
  /** An action: nothing happens until the first button is tapped. */
  buttons?: string[];
}

/** Відгук учасника після зустрічі малої групи (головна, блок «Малі групи»). */
export interface GroupFeedback {
  who: string;
  /** Коли залишили — зустріч уже скінчилась, це вечір того ж дня. */
  when: string;
  text: string;
  /** Позначка, під яку відгук ліг у систему: напр. молитовна потреба. */
  tag?: string;
}

